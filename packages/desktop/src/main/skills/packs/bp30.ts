const ID = "bp30"
const VERIFIED_ON = "3.0.205.22"

function frontmatter(name: string, description: string): string {
  return ["---", `name: ${name}`, `description: ${description.replace(/\s+/g, " ").trim()}`, "---", ""].join("\n")
}

