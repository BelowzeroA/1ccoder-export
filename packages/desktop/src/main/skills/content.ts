// The bundled skill set.
//
// Skills are generated at startup rather than shipped as static files, because
// each one needs absolute paths that are only known at runtime: where the
// v8pack launcher was written, and which directory the agent should work in.
// A static SKILL.md would have to describe those paths in prose and hope the
// agent guessed right.
//
// Naming matters here. Skills that need a live infobase are prefixed
// `1ccoder-ib-` so that one permission rule hides all of them from the
// profile-less agent -- see agents.ts.

import { INFOBASE_SKILL_PREFIX } from "./agents"
import { MCP_CLIENT_NAME, TOOLKIT_DIR_NAME, TOOLKIT_FILE_NAME } from "../mcp/toolkit"
import { PACKS } from "./packs"

export interface SkillFile {
  readonly name: string
  readonly body: string
}

export interface SkillContext {
  /** The command that runs v8pack, already quoted for a shell. */
  readonly v8pack: string
  /** Absolute path to the directory holding the bundled .epf starting points. */
  readonly templatesDir: string
  /** File names of those starting points, as installed. */
  readonly templates: readonly string[]
  /** Absolute path to the vendored MXL format specs. */
  readonly referenceDir: string
  /** Names of the vendored skills that were installed, if any. */
  readonly vendored: readonly string[]
}

