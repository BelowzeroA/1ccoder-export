function frontmatter(name: string, description: string): string {
  // Single-line description: the loader reads YAML, and a stray colon or line
  // break in a description is the easiest way to break a skill silently.
  return ["---", `name: ${name}`, `description: ${description.replace(/\s+/g, " ").trim()}`, "---", ""].join("\n")
}

